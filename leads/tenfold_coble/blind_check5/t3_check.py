"""T3 second method (MOD p, p = 1 mod 3, faithful because all entries are 0 or cube roots of 1):
explicit 12x12 matrices, group generated by matrix multiplication, invariants by linear algebra (common fixed space
of the generators acting on Q -> det(g) * Q(g x) on squarefree monomials modulo the squares)."""
import itertools
import flint
p = 2147483629
z = 2
while True:
    w = pow(z, (p - 1) // 3, p)
    if w != 1:
        break
    z += 1
R = lambda k: 2*(k % 3); Y = lambda k: 2*(k % 3)+1; P = lambda i: 6+2*(i % 3); Q = lambda i: 7+2*(i % 3)
def mat_from_sub(sub):
    """sub[v] = (coef, target): x_v -> coef * x_target ; matrix A with (g x)_v = sum_u A[v][u] x_u"""
    A = [[0]*12 for _ in range(12)]
    for v, (c, t) in sub.items():
        A[v][t] = c % p
    return A
sh = {}; c = {}; b = {}; io = {}
for k in range(3):
    sh[R(k)] = (1, R(k+2)); sh[Y(k)] = (1, Y(k+2)); sh[P(k)] = (1, P(k+1)); sh[Q(k)] = (1, Q(k+1))
    c[R(k)] = (pow(w, k, p), R(k)); c[Y(k)] = (pow(w, k, p), Y(k)); c[P(k)] = (pow(w, (-k) % 3, p), P(k)); c[Q(k)] = (pow(w, (-k) % 3, p), Q(k))
    b[R(k)] = (1, R(k)); b[Y(k)] = (1, Y(k)); b[P(k)] = (w, P(k)); b[Q(k)] = (w*w, Q(k))
    io[R(k)] = (1, R(-k)); io[Y(k)] = (1, Y(-k)); io[P(k)] = (1, Q(-k)); io[Q(k)] = (1, P(-k))
gens = [mat_from_sub(s) for s in (sh, c, b, io)]
def mul(A, B):
    return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(12)) % p for j in range(12)) for i in range(12))
gens = [tuple(tuple(r) for r in g) for g in gens]
I = tuple(tuple(1 if i == j else 0 for j in range(12)) for i in range(12))
elems = {I}; frontier = [I]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            gh = mul(g, h)
            if gh not in elems:
                elems.add(gh); new.append(gh)
    frontier = new
print("order of the matrix group generated mod p:", len(elems))
dets = [int(flint.nmod_mat(12, 12, [t for r in g for t in r], p).det()) for g in gens]
print("determinants of sh, c, b, iota mod p (p-1 means -1):", dets)
for deg in (0, 3, 6, 9, 12):
    mons = list(itertools.combinations(range(12), deg))
    idx = {m: i for i, m in enumerate(mons)}
    rows = []
    for g, dg in zip(gens, dets):
        # image of monomial prod x_v: prod (coef_v x_(t_v)) ; twisted by det
        img = {}
        for v in range(12):
            t = [u for u in range(12) if g[v][u]][0]
            img[v] = (g[v][t], t)
        for m in mons:
            coef = dg
            tm = []
            for v in m:
                coef = coef * img[v][0] % p
                tm.append(img[v][1])
            row = [0]*len(mons)
            row[idx[tuple(sorted(tm))]] = coef
            row[idx[m]] = (row[idx[m]] - 1) % p
            rows.append(row)
    M = flint.nmod_mat(len(rows), len(mons), [t for r in rows for t in r], p)
    print(f"degree {deg}: dim of the common fixed space = {len(mons) - M.rank()}")
