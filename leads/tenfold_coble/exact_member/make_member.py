#!/usr/bin/env python3
"""Write the member for candidate c and w-part option W (1 or 2) as a Macaulay2 file that expects kk to be defined.
usage: make_member.py c W  > member_c_W.m2"""
import sys, random, itertools
c = int(sys.argv[1]); W = int(sys.argv[2])
yv = ["z_0","z_1","z_2","p_0","p_1","p_2","q_0","q_1","q_2"]
# the 45 quadratic monomials in y, in lexicographic order of exponent vectors (first variable first)
mons = []
for e in itertools.product(range(3), repeat=9):
    if sum(e) == 2: mons.append(e)
mons.sort(reverse=True)
assert len(mons) == 45
def mstr(e):
    return "*".join(yv[i] if e[i] == 1 else yv[i] + "^2" for i in range(9) if e[i] > 0)
rng = random.Random(1000 + c)
phis = []
for k in range(3):
    ms = rng.sample(mons, 6)
    terms = []
    for m in ms:
        cf = rng.choice([-2, -1, 1, 2])
        terms.append("(%d)*%s" % (cf, mstr(m)))
    phis.append(" + ".join(terms))
print("-- member: candidate c = %d, w-part option W%d (generated by make_member.py; rule in PREREG_exact.md)" % (c, W))
print("S = kk[z_0..z_2, p_0..p_2, q_0..q_2, w_0..w_2];")
print("hC = (a, b, c) -> a^3 + b^3 + c^3 + 9*a*b*c;")
print("zz = {z_0,z_1,z_2}; ps = {p_0,p_1,p_2}; qs = {q_0,q_1,q_2}; xm = {4,3,3};")
print("Mten = sum flatten apply(3, i -> apply(3, j -> xm#((i-j)%3) * zz#((i+j)%3) * ps#i * qs#j));")
print("F8 = -221*hC(z_0,z_1,z_2) + 378*hC(p_0,p_1,p_2) + 378*hC(q_0,q_1,q_2) + 378*Mten;")
for k in range(3):
    print("Phi%d = %s;" % (k, phis[k]))
w = "w_0^3 + w_1^3 + w_2^3" + (" + w_0^2*z_0 + w_1^2*p_1 + w_2^2*q_2" if W == 2 else "")
print("Wpart = %s;" % w)
print("F = F8 + w_0*Phi0 + w_1*Phi1 + w_2*Phi2 + Wpart;")
